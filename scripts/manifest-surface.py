#!/usr/bin/env python3
"""The release app's permissions and the parts of it other apps can reach.

Reads the merged release manifest (ours plus every library's) and writes a
short summary to docs/manifest-surface.txt. With --check it fails when the
summary differs from the committed one, so a dependency that adds a
permission, an exported component or a provider shows up in review instead of
in a release. Run after `./gradlew :app:processReleaseManifest`; after an
intended change, run it without --check and commit the result.
"""
import difflib
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "app/build/intermediates/merged_manifests/release/processReleaseManifest/AndroidManifest.xml"
OUT = ROOT / "docs/manifest-surface.txt"
A = "{http://schemas.android.com/apk/res/android}"

HEADER = """\
# What the release app may do and what other apps can reach in it, from the merged
# release manifest (all libraries included). Generated by scripts/manifest-surface.py;
# CI fails when it differs. exported=default means not exported (no intent filter).
"""


def attr(el, name, default="-"):
    return el.get(A + name, default)


def summary(manifest):
    root = ET.parse(manifest).getroot()
    app = root.find("application")
    lines = []
    lines.append("application " + " ".join(f"{n}={attr(app, n)}" for n in (
        "allowBackup", "dataExtractionRules", "fullBackupContent", "networkSecurityConfig",
        "usesCleartextTraffic", "debuggable", "requestLegacyExternalStorage")))
    for md in app.findall("meta-data"):
        lines.append(f"application meta-data {attr(md, 'name')}={attr(md, 'value', attr(md, 'resource'))}")
    for tag in ("uses-permission", "uses-permission-sdk-23"):
        for p in root.findall(tag):
            extra = f" maxSdkVersion={attr(p, 'maxSdkVersion')}" if attr(p, "maxSdkVersion") != "-" else ""
            lines.append(f"permission {attr(p, 'name')}{extra}")
    for p in root.findall("permission"):
        lines.append(f"permission-defined {attr(p, 'name')} protectionLevel={attr(p, 'protectionLevel')}")
    for q in root.findall("queries"):
        for child in q:
            lines.append(f"queries {child.tag} {attr(child, 'name', ET.tostring(child, encoding='unicode').strip())}")
    for tag in ("activity", "activity-alias", "service", "receiver", "provider"):
        for c in app.findall(tag):
            filters = c.findall("intent-filter")
            exported = attr(c, "exported", "default" if not filters else "missing")
            parts = [tag, attr(c, "name"), f"exported={exported}"]
            for n in ("permission", "readPermission", "writePermission", "authorities", "grantUriPermissions", "foregroundServiceType"):
                if attr(c, n) != "-":
                    parts.append(f"{n}={attr(c, n)}")
            actions = sorted({attr(a, "name") for f in filters for a in f.findall("action")})
            if actions:
                parts.append("actions=" + ",".join(actions))
            lines.append(" ".join(parts))
    return HEADER + "".join(l + "\n" for l in sorted(lines))


def main():
    if not MANIFEST.exists():
        sys.exit(f"{MANIFEST.relative_to(ROOT)} is missing: run ./gradlew :app:processReleaseManifest first")
    text = summary(MANIFEST)
    if "--check" not in sys.argv[1:]:
        OUT.write_text(text)
        return
    old = OUT.read_text() if OUT.exists() else ""
    if old != text:
        sys.stdout.writelines(difflib.unified_diff(old.splitlines(True), text.splitlines(True), str(OUT.relative_to(ROOT)), "release manifest now"))
        print(f"::error file={OUT.relative_to(ROOT)}::The release app's permissions or exported parts changed. "
              "If intended, run scripts/manifest-surface.py and commit the result.")
        sys.exit(1)
    print("Permissions and exported components as committed.")


if __name__ == "__main__":
    main()
